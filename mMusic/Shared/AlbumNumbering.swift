import Foundation
import SwiftData

/// Починка номеров треков в альбомах: проход по библиотеке на запуске.
///
/// Номер на экране — это `position + 1`, поэтому съехавшая на единицу нумерация
/// показывала «2» у единственного трека альбома. Съезжали они там, где альбом
/// треку ставили присваиванием, а номер брали по `album.tracks.count`: трек к
/// этому моменту уже был в альбоме и считал сам себя. Само присваивание больше
/// не используется — номер выдаёт `Album.append`, — но у тех, кто успел собрать
/// библиотеку раньше, номера так и остались сбитыми, и починить их можно только
/// пересчётом.
///
/// Пересчёт ничего не удаляет и не переставляет: он идёт по нынешнему порядку и
/// только смыкает номера. Альбомы, где всё в порядке, не трогает вовсе.
enum AlbumNumbering {

    /// Сколько альбомов пришлось пересчитать. Ноль — обычное дело: проход
    /// повторяется на каждом запуске и в исправной библиотеке ничего не пишет.
    @discardableResult
    @MainActor
    static func repair(in context: ModelContext) -> Int {
        let albums = (try? context.fetch(FetchDescriptor<Album>())) ?? []
        var repaired = 0

        for album in albums where !album.isNumberedInOrder {
            album.renumberTracks()
            repaired += 1
        }

        return repaired
    }
}
